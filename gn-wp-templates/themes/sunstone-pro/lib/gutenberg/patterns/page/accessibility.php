<h3 id="conformance-status"><strong>Conformance status</strong></h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The <a href="https://www.w3.org/WAI/standards-guidelines/wcag/">Web Content Accessibility Guidelines (WCAG)</a> defines requirements for designers and developers to improve accessibility for people with disabilities. It defines three levels of conformance: Level A, Level AA, and Level AAA. Sunstone Golf Club is partially conformant with WCAG 2.1 level AA. Partially conformant means that some parts of the content do not fully conform to the accessibility standard.</p>
<!-- /wp:paragraph -->

<!-- wp:image {"width":88,"linkDestination":"custom"} -->
<figure class="wp-block-image is-resized"><a href="https://www.w3.org/WAI/WCAG2AA-Conformance"><img src="https://www.w3.org/WAI/WCAG21/wcag2.1AA-v.png" alt="Level Double-A conformance, W3C WAI Web Content Accessibility Guidelines 2.1" width="88"/></a></figure>
<!-- /wp:image -->

<!-- wp:heading {"level":4} -->
<h4 id="additional-accessibility-considerations">Additional accessibility considerations</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Although our goal is WCAG 2.1 Level AA conformance, we have also applied some Level AAA Success Criteria including but not limited to no background audio, there are no images of text except the logo, all functionality is operable via keyboard, there are no time dependent tasks, there are no task interruptions, there are no flashes used on site, there are no motions that cannot be disabled, breadcrumbs and context aware navigation is used to provide location, link text purpose is clear, section headings are used to organize content, and inputs are not restricted.</p>
<!-- /wp:paragraph -->

